// Regenerates src/core/yamnet/labels.ts from the pinned yamnet_class_map.csv.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const csv = readFileSync(root + 'assets/model/yamnet_class_map.csv', 'utf8').trim().split('\n');

// Minimal CSV parse: index,mid,display_name where display_name may be quoted.
const labels = csv.slice(1).map((line, i) => {
  const m = /^(\d+),([^,]+),(?:"(.*)"|(.*))$/.exec(line.replace(/\r$/, ''));
  if (!m || Number(m[1]) !== i) throw new Error(`Unexpected CSV row ${i}: ${line}`);
  return m[3] ?? m[4];
});

const body = labels.map((l) => `  ${JSON.stringify(l)},`).join('\n');
writeFileSync(
  root + 'src/core/yamnet/labels.ts',
  `// Generated by scripts/gen-labels.mjs from assets/model/yamnet_class_map.csv. Do not edit.
// Order is the YAMNet output order: scores[i] belongs to YAMNET_LABELS[i].
export const YAMNET_LABELS: readonly string[] = [
${body}
];
`,
);
console.log(`wrote ${labels.length} labels`);
